"""Generate factual weekly and monthly documents; never calls a model."""

import argparse

import pandas as pd

from twil_demo.metrics import compute_summary, load_tables
from twil_demo.paths import DOCS, ensure_directories


def render_period(activities, daily, start, end, label):
    summary = compute_summary(activities, daily, start, end)
    days = daily[daily["date"].between(start, end)]
    lines = [f"# {label}: {start.date()} through {end.date()}", "",
             "Sources: data/clean/activities.parquet and data/clean/daily.parquet.",
             f"- Sessions: {summary['sessions']}; training hours: {summary['hours']}"]
    for sport, stats in summary["by_sport"].items():
        lines.append(f"- {sport}: {stats['sessions']} sessions, {stats['hours']} hours, {stats['distance_km']} km")
    for column, unit in (("sleep_hours", "hours"), ("resting_hr", "bpm"), ("weight_lb", "lb"), ("sleep_score", "points")):
        values = days[column]
        mean = f"{values.mean():.2f}" if values.count() else "unavailable"
        lines.append(f"- {column} average: {mean} {unit}; {values.count()} observed days of {(end-start).days+1} calendar days")
    lines.append("\nMissing measurements are unknown; averages include observed days only. Session counts include transitions but exclude multisport parent totals when legs exist.")
    return "\n".join(lines) + "\n"


def generate_summaries(activities, daily, directory=DOCS / "garmin"):
    directory.mkdir(parents=True, exist_ok=True)
    dates = pd.concat([frame["date"] for frame in (activities, daily) if not frame.empty])
    first, last = dates.min().normalize(), dates.max().normalize()
    expected = set()
    for frequency, prefix, label in (("W-SUN", "week", "Training week"), ("M", "month", "Training month")):
        periods = pd.period_range(first, last, freq=frequency)
        for period in periods:
            start, end = period.start_time.normalize(), min(period.end_time.normalize(), last)
            path = directory / f"{prefix}_{start.date()}.md"
            path.write_text(render_period(activities, daily, max(start, first), end, label), encoding="utf-8")
            expected.add(path.name)
    # Remove only files generated by this module, so removed source weeks cannot
    # remain retrievable after a later export replaces the tables.
    import re
    for path in directory.iterdir():
        if re.fullmatch(r"(?:week|month)_\d{4}-\d{2}-\d{2}\.md", path.name) and path.name not in expected:
            path.unlink()
    return len(expected)


def main():
    argparse.ArgumentParser(description=__doc__).parse_args()
    ensure_directories()
    print(f"Wrote {generate_summaries(*load_tables())} weekly/monthly documents in {DOCS / 'garmin'}")
    print("Run python -m twil_demo.rag_app index after refreshing summaries and trends.")


if __name__ == "__main__":
    main()
